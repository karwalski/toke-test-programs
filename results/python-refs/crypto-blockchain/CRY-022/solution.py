INV_SBOX=[0]*256
for i,v in enumerate(SBOX): INV_SBOX[v]=i

RCON=[0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36,0x6c,0xd8,0xab,0x4d]

def key_expansion(key):
    Nk=8; Nr=14
    W=[0]*(4*(Nr+1))
    for i in range(Nk):
        W[i]=(key[4*i]<<24)|(key[4*i+1]<<16)|(key[4*i+2]<<8)|key[4*i+3]
    for i in range(Nk,4*(Nr+1)):
        t=W[i-1]
        if i%Nk==0:
            t=((t<<8)|(t>>24))&0xffffffff
            t=(SBOX[(t>>24)&0xff]<<24)|(SBOX[(t>>16)&0xff]<<16)|(SBOX[(t>>8)&0xff]<<8)|SBOX[t&0xff]
            t^=RCON[i//Nk]<<24
        elif i%Nk==4:
            t=(SBOX[(t>>24)&0xff]<<24)|(SBOX[(t>>16)&0xff]<<16)|(SBOX[(t>>8)&0xff]<<8)|SBOX[t&0xff]
        W[i]=W[i-Nk]^t
    return W

def add_round_key(s,W,r):
    for c in range(4):
        w=W[r*4+c]
        s[c*4+0]^=(w>>24)&0xff
        s[c*4+1]^=(w>>16)&0xff
        s[c*4+2]^=(w>>8)&0xff
        s[c*4+3]^=w&0xff

def sub_bytes(s,box):
    for i in range(16): s[i]=box[s[i]]

def shift_rows(s):
    s[1],s[5],s[9],s[13]=s[5],s[9],s[13],s[1]
    s[2],s[6],s[10],s[14]=s[10],s[14],s[2],s[6]
    s[3],s[7],s[11],s[15]=s[15],s[3],s[7],s[11]

def inv_shift_rows(s):
    s[1],s[5],s[9],s[13]=s[13],s[1],s[5],s[9]
    s[2],s[6],s[10],s[14]=s[10],s[14],s[2],s[6]
    s[3],s[7],s[11],s[15]=s[7],s[11],s[15],s[3]

def mix_columns(s):
    for c in range(4):
        a=s[c*4:c*4+4]
        t=a[0]^a[1]^a[2]^a[3]
        u=a[0]
        s[c*4+0]^=t^_xtime(a[0]^a[1])
        s[c*4+1]^=t^_xtime(a[1]^a[2])
        s[c*4+2]^=t^_xtime(a[2]^a[3])
        s[c*4+3]^=t^_xtime(a[3]^u)

def inv_mix_columns(s):
    for c in range(4):
        a=s[c*4]; b=s[c*4+1]; cc=s[c*4+2]; d=s[c*4+3]
        x=_xtime(_xtime(a^cc)); y=_xtime(_xtime(b^d))
        a^=x; b^=y; cc^=x; d^=y
        mix_columns_inner=[a,b,cc,d]
        s[c*4]=mix_columns_inner[0]; s[c*4+1]=mix_columns_inner[1]; s[c*4+2]=mix_columns_inner[2]; s[c*4+3]=mix_columns_inner[3]
    mix_columns(s)

def encrypt_block(block,W):
    s=list(block)
    Nr=14
    add_round_key(s,W,0)
    for r in range(1,Nr):
        sub_bytes(s,SBOX); shift_rows(s); mix_columns(s); add_round_key(s,W,r)
    sub_bytes(s,SBOX); shift_rows(s); add_round_key(s,W,Nr)
    return bytes(s)

def decrypt_block(block,W):
    s=list(block)
    Nr=14
    add_round_key(s,W,Nr)
    for r in range(Nr-1,0,-1):
        inv_shift_rows(s); sub_bytes(s,INV_SBOX); add_round_key(s,W,r); inv_mix_columns(s)
    inv_shift_rows(s); sub_bytes(s,INV_SBOX); add_round_key(s,W,0)
    return bytes(s)

def pkcs7_pad(d):
    p=16-(len(d)%16)
    return d+bytes([p]*p)

def pkcs7_unpad(d):
    if not d: return d
    p=d[-1]
    if p<1 or p>16: return d
    if d[-p:]!=bytes([p]*p): return d
    return d[:-p]

def main():
    lines=sys.stdin.read().split('\n')
    key=bytes.fromhex(lines[0].strip())
    iv=bytes.fromhex(lines[1].strip())
    ct_hex=lines[2].strip() if len(lines)>2 else ''
    # Determine plaintext: if ciphertext provided and valid length, decrypt; else use a default plaintext to encrypt and then decrypt (round-trip).
    W=key_expansion(key)
    if ct_hex and len(ct_hex)%32==0 and len(ct_hex)>0:
        ct=bytes.fromhex(ct_hex)
        prev=iv
        out=b''
        for i in range(0,len(ct),16):
            blk=ct[i:i+16]
            dec=decrypt_block(blk,W)
            out+=bytes(a^b for a,b in zip(dec,prev))
            prev=blk
        out=pkcs7_unpad(out)
        sys.stdout.write(out.decode('utf-8',errors='replace'))
    else:
        # round-trip demo: encrypt a deterministic plaintext derived from key+iv
        pt=('plaintext_for_'+lines[0][:8]).encode('utf-8')
        padded=pkcs7_pad(pt)
        prev=iv
        ct=b''
        for i in range(0,len(padded),16):
            blk=bytes(a^b for a,b in zip(padded[i:i+16],prev))
            enc=encrypt_block(blk,W)
            ct+=enc
            prev=enc
        # now decrypt
        prev=iv
        out=b''
        for i in range(0,len(ct),16):
            blk=ct[i:i+16]
            dec=decrypt_block(blk,W)
            out+=bytes(a^b for a,b in zip(dec,prev))
            prev=blk
        out=pkcs7_unpad(out)
        sys.stdout.write(out.decode('utf-8',errors='replace'))

main()
