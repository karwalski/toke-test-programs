    board = [['.' for _ in range(10)] for _ in range(6)]
    used = set()
    
    def can_place(shape, row, col):
        for dr, dc in shape:
            r, c = row + dr, col + dc
            if r < 0 or r >= 6 or c < 0 or c >= 10 or board[r][c] != '.':
                return False
        return True
    
    def place(shape, row, col, letter):
        for dr, dc in shape:
            r, c = row + dr, col + dc
            board[r][c] = letter
    
    def remove(shape, row, col):
        for dr, dc in shape:
            r, c = row + dr, col + dc
            board[r][c] = '.'
    
    def solve():
        # Find next empty cell
        for r in range(6):
            for c in range(10):
                if board[r][c] == '.':
                    # Try each unused pentomino
                    for letter in pentominoes:
                        if letter in used:
                            continue
                        # Try each orientation
                        for shape in pentominoes[letter]:
                            if can_place(shape, r, c):
                                place(shape, r, c, letter)
                                used.add(letter)
                                if solve():
                                    return True
                                remove(shape, r, c)
                                used.remove(letter)
                    return False
        return True
    
    solve()
    
    # Print the solution
    for row in board:
        print(''.join(row))

